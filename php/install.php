<?php
/* One-time web installer: connects to your MySQL database, creates the tables, seeds the programs and creates the admin account.
   It locks itself once _app/config.php exists. Delete this file after installing. */
$cfgFile = __DIR__ . '/_app/config.php';
header('X-Frame-Options: DENY');
function h($s) { return htmlspecialchars((string)$s, ENT_QUOTES, 'UTF-8'); }
function page(string $body) {
  echo '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Finsang installer</title><style>
  body{font-family:system-ui,sans-serif;background:#f5f4ef;color:#11110f;margin:0;padding:24px}main{max-width:560px;margin:0 auto;background:#fff;border:1px solid #ddd;padding:28px}
  h1{margin:0 0 4px;font-size:1.4rem}p.s{color:#666;margin:0 0 20px}label{display:block;font-weight:600;font-size:.85rem;margin:14px 0 4px}
  input[type=text],input[type=password],input[type=email]{width:100%;box-sizing:border-box;padding:10px;border:1px solid #bbb;font-size:1rem}
  button{margin-top:22px;background:#11110f;color:#e6ca83;border:0;padding:12px 22px;font-weight:700;letter-spacing:.06em;text-transform:uppercase;cursor:pointer}
  .e{background:#fde8e8;border:1px solid #e99;padding:10px;margin:14px 0}.ok{background:#e6f6e6;border:1px solid #8c8;padding:10px;margin:14px 0}small{color:#777}h2{font-size:1rem;margin:26px 0 0;border-top:1px solid #eee;padding-top:16px}
  </style></head><body><main>' . $body . '</main></body></html>';
  exit;
}
if (is_file($cfgFile)) page('<h1>Already installed</h1><p class="s">The portal is set up. For safety, delete <b>install.php</b> from your hosting File Manager.</p><p><a href="/login.html">Go to the login page →</a></p>');

$err = ''; $v = ['db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'admin_email' => '', 'admin_name' => 'Administrator'];
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
  foreach ($v as $k => $_) $v[$k] = trim((string)($_POST[$k] ?? ''));
  $dbPass = (string)($_POST['db_pass'] ?? ''); $adminPass = (string)($_POST['admin_pass'] ?? '');
  try {
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) throw new Exception('Enter a valid admin email.');
    if (strlen($adminPass) < 10) throw new Exception('Choose an admin password of at least 10 characters.');
    if (!is_writable(__DIR__ . '/_app')) throw new Exception('The _app folder is not writable. Set its permissions to 755 (or 775) and retry.');
    $dsn = 'mysql:host=' . $v['db_host'] . ';dbname=' . $v['db_name'] . ';charset=utf8mb4';
    try { $db = new PDO($dsn, $v['db_user'], $dbPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]); }
    catch (PDOException $e) { throw new Exception('Could not connect to the database: ' . $e->getMessage()); }
    $conf = ['db_host' => $v['db_host'], 'db_name' => $v['db_name'], 'db_user' => $v['db_user'], 'db_pass' => $dbPass,
      'base_url' => ((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https' ? 'https://' : 'http://') . $_SERVER['HTTP_HOST'],
      'mail_from' => '', 'upload_dir' => ''];
    file_put_contents($cfgFile, "<?php\n// Generated by install.php. Keep this file private.\nreturn " . var_export($conf, true) . ";\n");
    @chmod($cfgFile, 0640);
    require __DIR__ . '/_app/lib/db.php';
    require __DIR__ . '/_app/lib/seed.php';
    install_schema(pdo());
    seed_base($v['admin_email'], $adminPass, $v['admin_name'] ?: 'Administrator');
    if (!empty($_POST['demo'])) seed_demo();
    if (!is_dir(upload_dir())) throw new Exception('Could not create the uploads folder.');
    page('<h1>Installed ✔</h1><div class="ok">Database tables, the 5 programs and your admin account were created.</div>
      <p><b>Next:</b></p><ol><li>Delete <b>install.php</b> from File Manager.</li><li><a href="/login.html">Log in</a> with <b>' . h($v['admin_email']) . '</b> and the password you chose.</li></ol>');
  } catch (Throwable $e) {
    if (is_file($cfgFile) && !isset($db)) @unlink($cfgFile);
    elseif (is_file($cfgFile) && !$db->query("SHOW TABLES LIKE 'users'")->fetch()) @unlink($cfgFile);
    $err = $e->getMessage();
  }
}
page('<h1>Finsang portal installer</h1><p class="s">Create a MySQL database in hPanel first (Databases → MySQL Databases), then enter its details here.</p>'
  . ($err ? '<div class="e">' . h($err) . '</div>' : '') . '
<form method="post" autocomplete="off"><h2 style="border:0;padding:0;margin-top:0">Database</h2>
<label>Host</label><input type="text" name="db_host" value="' . h($v['db_host']) . '" required><small>Usually <b>localhost</b>.</small>
<label>Database name</label><input type="text" name="db_name" value="' . h($v['db_name']) . '" required>
<label>Database user</label><input type="text" name="db_user" value="' . h($v['db_user']) . '" required>
<label>Database password</label><input type="password" name="db_pass">
<h2>Admin account</h2><label>Name</label><input type="text" name="admin_name" value="' . h($v['admin_name']) . '">
<label>Email</label><input type="email" name="admin_email" value="' . h($v['admin_email']) . '" required>
<label>Password (10+ characters)</label><input type="password" name="admin_pass" required minlength="10">
<label style="font-weight:400;margin-top:18px"><input type="checkbox" name="demo" value="1"> Also load demo students and sample data <small>(leave unticked for a real launch)</small></label>
<button>Install</button></form>');
